import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const path='src/lib/financeCodFilters.ts';
assert.ok(fs.existsSync(path),'COD queue must support date, crew, van, payment and age filters');
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{module,exports:module.exports});
const {filterCodRows,codServiceDate,codDuration}=module.exports;
const now=Date.parse('2026-10-23T06:30:00Z');
const rows=[{delivery_way_id:'D1',wayplan_id:'W1',driver_name:'Aung',settlement_status:'PENDING_SETTLEMENT',delivered_at:'2026-10-20T20:00:00Z',metadata:{source_business_date:'2026-10-21',merchant_name:'Baby World',vehicle_plate:'1H-6033',reported_payment_allocations:[{method:'CASH',amount:30},{method:'KBZ_PAY',amount:70}]}},{delivery_way_id:'D2',settlement_status:'SETTLED',delivered_at:'2026-10-22T00:00:00Z',settled_at:'2026-10-22T02:00:00Z',metadata:{payment_method:'CASH'}},{delivery_way_id:'D3',settlement_status:'PENDING_SETTLEMENT',metadata:{}}];
assert.equal(codServiceDate({delivered_at:'2026-10-20T20:00:00Z'}),'2026-10-21','Dates use Myanmar local time');
assert.equal(filterCodRows(rows,{from:'2026-10-21',to:'2026-10-21',payment:'KBZ_PAY',worker:'aung',van:'6033',merchant:'baby'},now).length,1);
assert.equal(filterCodRows(rows,{payment:'CASH'},now).length,2,'Mixed receipts participate in each payment method');
assert.equal(filterCodRows(rows,{from:'2026-10-23',to:'2026-10-20'},now).length,0);
assert.equal(filterCodRows(rows,{status:'SETTLED'},now)[0].delivery_way_id,'D2');
assert.equal(filterCodRows(rows,{duration:'OVER_48H'},now)[0].delivery_way_id,'D1');
assert.equal(codDuration(rows[1],now),'2h 0m','Completed duration stops at settlement');
assert.equal(codDuration(rows[2],now),'Not recorded');
assert.equal(filterCodRows(rows,{query:'W1'},now).length,1);
console.log('PASS Finance COD filters: split methods, MMT dates, period boundaries, crew/van, unknown dates and elapsed settlement duration');
