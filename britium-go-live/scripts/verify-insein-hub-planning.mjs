import assert from "node:assert/strict";
import {planInseinHub,inseinTownship,INSEIN_HUB} from "../src/lib/inseinHubPlanner.mjs";
const make=(id,township)=>({delivery_way_id:id,township});
assert.equal(inseinTownship("လှိုင်သာယာ (အရှေ့ပိုင်း)"),"Hlaingthaya");
assert.equal(inseinTownship("Mayangon Township"),"Mayangone");
assert.equal(inseinTownship("Shwe Pyi Thar"),"Shwepyitha");
const plan=planInseinHub({deliveries:[make("A","Insein"),make("B","Hlaing Thar Yar"),make("C","Shwe Pyi Thar"),make("D","Mayangone")],pickups:[make("P1","Insein")],returns:[make("R1","Mayangone")],riderCount:2,shuttleWindow:"EVENING"});
assert.equal(plan.inbound_shuttle.parcel_count,4);
assert.equal(plan.outbound_shuttle.parcel_count,2);
assert.equal(plan.rider_routes.length,2);
assert.equal(plan.rider_routes.reduce((n,r)=>n+r.parcel_count,0),4);
assert.equal(plan.hub.latitude,16.8914722);
assert.equal(INSEIN_HUB.branchCode,"YGN-INS");
assert.equal(plan.inbound_shuttle.status,"DRAFT_UNSCANNED");
assert.equal(plan.local_pickup_queue.length,1);
assert.equal(planInseinHub({deliveries:[make("SMALL","Insein")],riderCount:1}).rider_routes[0].parcel_count,1);
assert.throws(()=>planInseinHub({deliveries:[make("X","Insein")],pickups:[make("X","Mayangone")]}),/two active queues/);
assert.throws(()=>planInseinHub({deliveries:[make("X","Bahan")]}),/does not belong/);
assert.throws(()=>planInseinHub({shuttleWindow:"MIDDAY"}),/Shuttle window/);
console.log("PASS Insein hub: aliases, manifests, rider routes, no minimum, duplicate fence, and windows");
