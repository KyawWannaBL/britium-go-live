import assert from "node:assert/strict";
import {createRequire} from "node:module";
import {normalizeWarehouseScan} from "../src/lib/warehouseScan.ts";
const require=createRequire(import.meta.url);
const z=require("@zxing/library");
const {BrowserMultiFormatReader}=require("@zxing/browser");
const way="P0911-BLK-289-001";
assert.equal(normalizeWarehouseScan("  "+way+"\r\n"),way);
assert.equal(normalizeWarehouseScan("]C0"+way),way);
assert.equal(normalizeWarehouseScan("]Q3"+way),way);
for(const bad of ["","https://example.com/"+way,"<script>","A\nB","x".repeat(129)])
 assert.throws(()=>normalizeWarehouseScan(bad));
function decode(data,width,height) {
 const bitmap=new z.BinaryBitmap(new z.HybridBinarizer(new z.RGBLuminanceSource(data,width,height)));
 return normalizeWarehouseScan(new BrowserMultiFormatReader().decodeBitmap(bitmap).getText());
}
const qr=new z.QRCodeWriter().encode(way,z.BarcodeFormat.QR_CODE,280,280,new Map());
const pixels=new Uint8ClampedArray(280*280);
for(let y=0;y<280;y++)for(let x=0;x<280;x++)pixels[y*280+x]=qr.get(x,y)?0:255;
assert.equal(decode(pixels,280,280),way);
// Code 128 pattern independently generated by ReportLab for this exact waybill.
// Uppercase segments are black; letter position is module width.
const pattern="BaAbAdCaCaBaAbCaBbCbAaBbAbCbBaAbCbBaAbBaCbAcAaBcAcBaCaAaBcCaAbBaCbBbCbAaCaAbBbCbAaBbAbBaCbAbCaBbAbCaBbAbCbBaAcDaAaBcCaAaB";
const modules=Array.from(pattern,c=>c.toLowerCase().charCodeAt(0)-96);
const width=(modules.reduce((a,b)=>a+b,0)+40)*3,height=160;
const barcode=new Uint8ClampedArray(width*height).fill(255);
let left=60;
Array.from(pattern).forEach((c,i)=>{
 const w=modules[i]*3;
 if(c===c.toUpperCase()) for(let y=20;y<140;y++)barcode.fill(0,y*width+left,y*width+left+w);
 left+=w;
});
assert.equal(decode(barcode,width,height),way);
