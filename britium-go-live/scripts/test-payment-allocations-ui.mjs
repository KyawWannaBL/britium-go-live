import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const module={exports:{}};
const file='src/lib/paymentAllocations.ts';
if(fs.existsSync(file))vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{module,exports:module.exports});
const {validatePaymentAllocations,reportedPaymentDraft,paymentAllocationLabel}=module.exports;
assert.equal(typeof validatePaymentAllocations,'function','split-payment validation must exist');
const split=[{method:'CASH',amount:'30000',reference:''},{method:'KBZ_PAY',amount:'20000',reference:'KBZ-1'}];
assert.equal(validatePaymentAllocations(split,'50000'),null);
assert.match(validatePaymentAllocations(split,'50001'),/equal/i);
assert.match(validatePaymentAllocations([{method:'KBZ_PAY',amount:'1',reference:''}],'1'),/reference/i);
for(const amount of ['-1','0','1.001','NaN','Infinity','1e3'])assert.ok(validatePaymentAllocations([{method:'CASH',amount,reference:''}],amount));
assert.equal(validatePaymentAllocations([],'0'),null);
assert.match(validatePaymentAllocations(Array.from({length:21},()=>({method:'CASH',amount:'1',reference:''})),'21'),/20/);
assert.ok(validatePaymentAllocations([{method:'CASH',amount:'90071992547409.91',reference:''},{method:'CASH',amount:'0.01',reference:''}],'90071992547409.91'));
assert.equal(validatePaymentAllocations([{method:'CASH',amount:'0.10',reference:''},{method:'QR',amount:'0.20',reference:'QR1'}],'0.30'),null);
assert.match(validatePaymentAllocations([{method:'UNKNOWN',amount:'1',reference:'R'}],'1'),/type/i);
assert.equal(reportedPaymentDraft({metadata:{payment_allocations:[{method:'CASH',amount:10,reference:''}],reported_payment_allocations:split},cod_collected:10}).allocations[0].amount,'10');
assert.ok(validatePaymentAllocations([],''));
assert.deepEqual(JSON.parse(JSON.stringify(reportedPaymentDraft({metadata:{historical_source_review:true},cod_expected:50000}))),{actual:'',allocations:[]});
assert.equal(reportedPaymentDraft({metadata:{reported_payment_allocations:split},cod_collected:50000}).actual,'50000');
assert.match(paymentAllocationLabel({metadata:{reported_payment_allocations:split}}),/Cash 30,000.*KBZ Pay 20,000/);
console.log('PASS split payments: exact totals, references, precision, zero, historical blanks and split labels');
