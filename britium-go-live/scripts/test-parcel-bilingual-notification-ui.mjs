import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const root=path.resolve(import.meta.dirname,"..");
const repo=path.resolve(root,"..");
const source=p=>fs.readFileSync(path.join(root,p),"utf8");
const sql=fs.readFileSync(path.join(repo,"sql/parcel_bilingual_targeted_alerts_v1_20261122.sql"),"utf8");
const composer=source("src/components/parcel/ParcelActionComposer.tsx");
const control=source("src/pages/HarmonizedParcelControlPage.tsx");
const follow=source("src/pages/ParcelFollowUpPage.tsx");
const report=source("src/lib/parcelReportExport.ts");
const check=(s,re,name)=>assert.match(s,re,name);
check(sql,/auth\.uid\(\) IS NOT NULL|v_actor IS NULL/,"server authentication gate");
check(sql,/be_current_role\(\)/,"server role gate");
check(sql,/REVOKE ALL ON FUNCTION public\.be_parcel_send_targeted_alert_v1/,"privileged RPC revoked");
check(sql,/u\.auth_user_id=p_recipient_user_id/,"specific recipient guard");
check(sql,/v_dept<>p_department/,"department membership guard");
check(sql,/v_total>40/,"department recipient cap");
check(sql,/notification_request_id/,"idempotent alert request");
check(sql,/ON CONFLICT DO NOTHING/,"duplicate suppression");
check(sql,/target_user_id,target_email/,"targeted notification insert");
check(sql,/source_table,source_key/,"audit source tracking");
assert.doesNotMatch(sql,/UPDATE\s+public\.be_finance_/i,"do not post financial entries");
assert.doesNotMatch(sql,/UPDATE\s+public\.be_waybill_/i,"do not falsify delivery status");
for(const [key,s] of [["control",control],["follow-up",follow]]){
 check(s,/ParcelActionComposer/,key+" bilingual composer");
 check(s,/type="date"/,key+" date filters");
 check(s,/Export Excel|exportExcel|excel\(/,key+" Excel export");
 check(s,/Export PDF|Save as PDF|exportPdf|pdf\(/,key+" PDF export");
 check(s,/warehouseFilter/,key+" warehouse status filter");
}
check(composer,/DEPARTMENT/, "department messaging");
check(composer,/PERSON/, "individual messaging");
check(composer,/မြန်မာ/, "Myanmar message presets");
check(composer,/English message/, "English custom editor");
check(composer,/textarea/, "custom bilingual notes");
check(composer,/be_parcel_send_targeted_alert_v1/, "server-side send RPC");
check(report,/untilMyanmarDay/,"Myanmar registration day boundaries");
check(report,/sanitizeExcel/,"CSV/XLSX formula escape");
check(report,/Report Context/,"source evidence disclaimer");
console.log("PASS: bilingual targeted notification, server recipient guardrails, timeline exports and action buttons");
