import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const require=createRequire(import.meta.url),file='src/components/warehouse/WarehouseReportedHistory.tsx';
assert.ok(fs.existsSync(file),'Warehouse queue needs a reported-history view');
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}}).outputText,{module,exports:module.exports,require},{filename:file});
const {WarehouseReportedHistory,reportedDateMatches}=module.exports;
const history=[{work_date:'2026-10-20',wayplan_id:'WP-20',reported_outcome:'DELIVERY_ATTEMPT_FAILED',reason:'<no answer>',verification:'Valid',driver_name:'Driver A'},{work_date:'2026-10-21',wayplan_id:'WP-21',reported_outcome:'THIRD_PARTY_HANDOVER_COMPLETE'}];
const html=renderToStaticMarkup(React.createElement(WarehouseReportedHistory,{history}));
assert.match(html,/2026-10-20/);assert.match(html,/WP-20/);assert.match(html,/Valid/);assert.match(html,/Driver A/);
assert.match(html,/&lt;no answer&gt;/);assert.doesNotMatch(html,/<no answer>/);
assert.match(html,/Reported/);assert.match(html,/Scan evidence is separate/);
assert.equal(reportedDateMatches({reported_source_history:history},'2026-10-20','2026-10-20'),true,'a later reattempt must not hide the earlier source date');
assert.equal(reportedDateMatches({reported_source_history:history},'2026-10-22','2026-10-22'),false);
for(const malformed of [null,{},[null],['x']])assert.doesNotThrow(()=>renderToStaticMarkup(React.createElement(WarehouseReportedHistory,{history:malformed})));
assert.equal(reportedDateMatches({},'2026-10-20','2026-10-21'),false,'actual scan dates do not become source operation dates');
console.log('PASS Warehouse reported-history display: source reasons/classification, escaping, dates and evidence distinction');
