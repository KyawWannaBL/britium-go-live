create or replace function public.be_business_date()
returns date language sql stable set search_path to 'public','pg_temp'
as $$
  select (statement_timestamp() at time zone 'Asia/Yangon')::date;
$$;

create table if not exists public.be_parcel_tariffs_v2 (
  id bigint generated by default as identity primary key,
  township text not null,
  customer_tier text not null
    check (customer_tier in ('STANDARD','ROYAL','COMMITMENT')),
  tariff_zone text not null,
  tariff_zone_code text not null,
  base_tariff bigint not null,
  included_kg numeric not null,
  extra_per_kg bigint not null,
  commitment_min_ways integer not null default 0,
  commitment_refund_per_way bigint not null default 0,
  note text,
  status text not null default 'ACTIVE'
    check (status in ('ACTIVE','INACTIVE')),
  effective_from date not null default public.be_business_date(),
  effective_to date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint be_parcel_tariffs_v2_amount_check
    check (base_tariff > 0 and included_kg >= 0 and extra_per_kg >= 0
      and commitment_min_ways >= 0 and commitment_refund_per_way >= 0),
  constraint be_parcel_tariffs_v2_version_unique
    unique (township, customer_tier, effective_from)
);
