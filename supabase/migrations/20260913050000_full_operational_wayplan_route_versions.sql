   if helper is not null and coalesce(helper->>'branch_code','') not in ('',branch) then raise exception 'Helper belongs to another branch.'; end if;
   if upper(p->>'driver_code')=upper(p->>'rider_code') or (helper is not null and upper(p->>'helper_code') in (upper(p->>'driver_code'),upper(p->>'rider_code'))) then raise exception 'Driver, Rider and Helper must be different people.'; end if;
   if (p->>'driver_code')=any(crews) or (p->>'rider_code')=any(crews) or (coalesce(p->>'helper_code','')<>'' and (p->>'helper_code')=any(crews)) then raise exception 'A workforce member cannot serve two positions or vans in this plan.'; end if;
   crews:=array_append(crews,p->>'driver_code'); crews:=array_append(crews,p->>'rider_code'); if helper is not null then crews:=array_append(crews,p->>'helper_code'); end if;
   if exists(select 1 from jsonb_array_elements(ctx->'busy') b where b->>'vehicle_code'=p->>'vehicle_code' or p->>'driver_code' in (b->>'driver_code',b->>'rider_code',b->>'helper_code') or p->>'rider_code' in (b->>'driver_code',b->>'rider_code',b->>'helper_code') or (helper is not null and p->>'helper_code' in (b->>'driver_code',b->>'rider_code',b->>'helper_code'))) then raise exception 'A selected vehicle or crew member already has an active Wayplan. Refresh availability.'; end if;
   for parcel_id in select jsonb_array_elements_text(p->'delivery_way_ids') loop if parcel_id=any(ids) then raise exception 'A parcel cannot belong to two vans.'; end if; ids:=array_append(ids,parcel_id); end loop;
   select coalesce(sum(weight_kg),0) into weight from public.be_data_entry_parcel_details where delivery_way_id in (select jsonb_array_elements_text(p->'delivery_way_ids'));
   if coalesce((v->>'capacity_kg')::numeric,0)>0 and weight>(v->>'capacity_kg')::numeric then raise exception 'Selected parcel weight exceeds vehicle capacity.'; end if;
   route:=coalesce(p->'route','{}'::jsonb); route_source:=upper(coalesce(route->>'source','GEOGRAPHIC_FALLBACK')); route_mode:=coalesce(route->>'route_mode','GEOGRAPHIC_NEAREST_NEIGHBOUR_EMERGENCY');
   if route_source not in ('GOOGLE_ROUTES','MAPBOX_FALLBACK','GEOGRAPHIC_FALLBACK') then raise exception 'Invalid route source.'; end if;
 end loop;
 if short_count>1 then raise exception 'Only one delivery van may be below 50 parcels.'; end if;
