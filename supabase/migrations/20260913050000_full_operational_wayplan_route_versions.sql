before insert or update of driver_code,rider_code,helper_code on public.be_wayplan_dispatches
for each row execute function public.be_wayplan_distinct_crew_guard_v1();

-- Keep existing assignment source, but expose Rider and all three active branch origins.
create or replace function public.be_multi_van_context()
returns jsonb language plpgsql stable security definer set search_path=public,auth,pg_temp as $$
declare
  v_options jsonb; v_vehicles jsonb; v_busy jsonb; v_role text; v_origins jsonb:='{}'::jsonb;
begin
  v_role:=lower(public.be_current_user_role());
  if auth.uid() is null or v_role not in ('superadmin','super_admin','admin','dispatch','wayplan_operator','supervisor') then
    raise exception using errcode='42501',message='Wayplan operator permission is required.';
  end if;
  v_options:=public.be_wayplan_assignment_options_v44();
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',record_key,'name',payload->>'vehicle_no','capacity_kg',payload->'capacity_kg','operation_type',payload->>'operation_type'
  ) order by record_key),'[]'::jsonb) into v_vehicles
  from public.be_master_data_rows
  where dataset_key='fleet_master' and deleted_at is null
    and upper(coalesce(status,'ACTIVE'))='ACTIVE'
    and upper(coalesce(payload->>'status','ACTIVE')) in ('ACTIVE','ASSIGNED')
    and payload->>'operation_type' in ('DELIVERY','PICKUP_HIGHWAY');

  select coalesce(jsonb_agg(jsonb_build_object(
    'vehicle_code',vehicle_code,'driver_code',driver_code,'rider_code',rider_code,'helper_code',helper_code
  )),'[]'::jsonb) into v_busy
  from public.be_wayplan_dispatches
  where upper(coalesce(wayplan_status,'CREATED')) not in ('CANCELLED','COMPLETED','CLOSED');

  select coalesce(jsonb_object_agg(region_code,origin),'{}'::jsonb) into v_origins
  from (
    select case branch_code when 'YGN' then 'YANGON' when 'MDY' then 'MANDALAY' when 'NPT' then 'NAYPYITAW' end region_code,
      jsonb_build_object('branch_code',branch_code,'label',branch_name,'latitude',lat,'longitude',lng) origin
    from public.be_branch_offices
    where branch_code in ('YGN','MDY','NPT') and coalesce(active,true)=true and lat is not null and lng is not null
  ) q where region_code is not null;

  return jsonb_build_object('vehicles',v_vehicles,'drivers',v_options->'drivers','riders',v_options->'riders','helpers',v_options->'helpers','busy',v_busy,'route_origins',v_origins);
end $$;
revoke all on function public.be_multi_van_context() from public,anon;
grant execute on function public.be_multi_van_context() to authenticated;

-- Append an immutable active road route version. Warehouse snapshot is never touched here.
create or replace function public.be_wayplan_append_route_version_v1(p_payload jsonb)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare
  v_wayplan text:=nullif(btrim(p_payload->>'wayplan_id'),'');
  v_scope text:=upper(coalesce(nullif(p_payload->>'route_scope',''),'RIDER_REROUTE'));
  v_source text:=upper(coalesce(nullif(p_payload->>'route_source',''),'GEOGRAPHIC_FALLBACK'));
  v_mode text:=coalesce(nullif(p_payload->>'route_mode',''),'GEOGRAPHIC_NEAREST_NEIGHBOUR_EMERGENCY');
  v_stops jsonb:=coalesce(p_payload->'ordered_stops','[]'::jsonb);
  v_actor text:=coalesce(public.be_field_team_code_from_login_v51(coalesce(auth.jwt()->>'email','')),auth.uid()::text);
  v_role text:=lower(public.be_current_user_role());
  v_current integer; v_next integer; v_ids text[]; v_expected text[]; v_item jsonb; v_seq integer:=0;
begin
  if auth.uid() is null then raise exception using errcode='42501',message='Authenticated Wayplan session required.'; end if;
  if v_wayplan is null then raise exception 'wayplan_id is required'; end if;
  if v_scope not in ('GENERATED','RIDER_REROUTE') then raise exception 'Invalid route scope'; end if;
  if v_source not in ('GOOGLE_ROUTES','MAPBOX_FALLBACK','GEOGRAPHIC_FALLBACK') then raise exception 'Invalid route source'; end if;
  if jsonb_typeof(v_stops)<>'array' or jsonb_array_length(v_stops)=0 then raise exception 'ordered_stops are required'; end if;

  perform 1 from public.be_wayplan_dispatches where wayplan_id=v_wayplan for update;
  if not found then raise exception 'Wayplan not found'; end if;

  if v_role in ('rider','driver','helper') and not exists(
    select 1 from public.be_wayplan_membership_v40 m where m.wayplan_id=v_wayplan and
      case v_role when 'driver' then upper(coalesce(m.driver_code,''))=upper(v_actor)
                  when 'helper' then upper(coalesce(m.helper_code,''))=upper(v_actor)
                  else upper(coalesce(m.rider_code,''))=upper(v_actor) end
  ) then raise exception using errcode='42501',message='Wayplan is not assigned to signed-in worker.'; end if;

  select array_agg(id order by id) into v_ids from (
    select btrim(value->>'delivery_way_id') id from jsonb_array_elements(v_stops) value
  ) s where id<>'';
  if cardinality(v_ids)<>jsonb_array_length(v_stops) or cardinality(v_ids)<>cardinality(array(select distinct unnest(v_ids))) then
    raise exception 'Every route stop requires one unique delivery_way_id';
  end if;

  if v_scope='RIDER_REROUTE' then
    select array_agg(delivery_way_id order by delivery_way_id) into v_expected
    from public.be_wayplan_dispatch_stops
    where wayplan_id=v_wayplan and upper(coalesce(stop_status,'')) not in ('DELIVERED','RETURN_TO_WAREHOUSE','RTO','SKIPPED','RESCHEDULED','CUSTOMER_UNAVAILABLE');
    if coalesce(v_ids,'{}'::text[]) is distinct from coalesce(v_expected,'{}'::text[]) then
      raise exception 'Rider reroute must contain every remaining eligible stop exactly once.';
    end if;
  end if;

  select max(route_version) into v_current from public.be_wayplan_route_versions_v1 where wayplan_id=v_wayplan;
  v_next:=coalesce(v_current,0)+1;
  insert into public.be_wayplan_route_versions_v1(
    wayplan_id,route_version,route_scope,route_source,route_mode,ordered_stops,distance_m,duration_s,request_count,parent_route_version,generated_by,metadata
  ) values (
    v_wayplan,v_next,v_scope,v_source,v_mode,v_stops,
    greatest(coalesce(nullif(p_payload->>'distance_m','')::bigint,0),0),
    greatest(coalesce(nullif(p_payload->>'duration_s','')::bigint,0),0),
    greatest(coalesce(nullif(p_payload->>'request_count','')::integer,0),0),
    v_current,v_actor,coalesce(p_payload->'metadata','{}'::jsonb)
  );

  -- Active road sequence may change; immutable warehouse snapshot does not.
  for v_item in select value from jsonb_array_elements(v_stops) loop
    v_seq:=v_seq+1;
    update public.be_wayplan_dispatch_stops
      set optimized_sequence=v_seq,
          route_code=v_wayplan||'-RV'||lpad(v_next::text,3,'0'),
          metadata=coalesce(metadata,'{}'::jsonb)||jsonb_build_object('active_route_version',v_next,'active_route_sequence',v_seq,'active_route_source',v_source),
          updated_at=now()
    where wayplan_id=v_wayplan and delivery_way_id=v_item->>'delivery_way_id';
  end loop;

  update public.be_wayplan_dispatches set metadata=coalesce(metadata,'{}'::jsonb)||jsonb_build_object(
    'generated_route_version',coalesce((metadata->>'generated_route_version')::integer,case when v_scope='GENERATED' then v_next else 1 end),
    'active_route_version',v_next,'active_route_source',v_source,'active_route_mode',v_mode
  ),updated_at=now() where wayplan_id=v_wayplan;

  return jsonb_build_object('ok',true,'wayplan_id',v_wayplan,'route_version',v_next,'route_scope',v_scope,'route_source',v_source);
end $$;
revoke all on function public.be_wayplan_append_route_version_v1(jsonb) from public,anon;
grant execute on function public.be_wayplan_append_route_version_v1(jsonb) to authenticated;

-- Route event snapshot for Rider Current Stop -> action -> Next Stop.
create or replace function public.be_wayplan_active_route_snapshot_v1(p_wayplan_id text)
returns jsonb language plpgsql stable security definer set search_path=public,auth,pg_temp as $$
declare v_version integer; v_source text; v_mode text; v_stops jsonb; v_current jsonb; v_warehouse integer; v_plan jsonb;
begin
  if auth.uid() is null then raise exception using errcode='42501',message='Authentication required.'; end if;
  select route_version,route_source,route_mode,ordered_stops into v_version,v_source,v_mode,v_stops
  from public.be_wayplan_route_versions_v1 where wayplan_id=p_wayplan_id order by route_version desc limit 1;
  if v_version is null then raise exception 'No generated route version exists for this Wayplan.'; end if;

  select generated_route_version into v_warehouse from public.be_wayplan_warehouse_load_snapshot_v1 where wayplan_id=p_wayplan_id;
  select to_jsonb(d) into v_plan from public.be_wayplan_dispatches d where d.wayplan_id=p_wayplan_id;

  select to_jsonb(q) into v_current from (
    select s.delivery_way_id,s.waybill_no,s.recipient_name,s.recipient_phone,s.address,s.township,s.stop_status,
      s.optimized_sequence as active_stop_sequence,
      s.metadata->>'notes' as notes,
      nullif(s.metadata#>>'{coordinates,latitude}','')::numeric as latitude,
      nullif(s.metadata#>>'{coordinates,longitude}','')::numeric as longitude
    from public.be_wayplan_dispatch_stops s
    where s.wayplan_id=p_wayplan_id and upper(coalesce(s.stop_status,'')) not in ('DELIVERED','RETURN_TO_WAREHOUSE','RTO','SKIPPED','RESCHEDULED','CUSTOMER_UNAVAILABLE')
    order by coalesce(s.optimized_sequence,s.stop_sequence),s.stop_sequence limit 1
  ) q;

  return jsonb_build_object('ok',true,'wayplan',v_plan,'route_version',v_version,'route_source',v_source,'route_mode',v_mode,
    'warehouse_generated_route_version',v_warehouse,'warehouse_route_immutable',true,'current_stop',v_current,
    'stops',(select coalesce(jsonb_agg(jsonb_build_object(
      'delivery_way_id',s.delivery_way_id,'waybill_no',s.waybill_no,'recipient_name',s.recipient_name,'recipient_phone',s.recipient_phone,
      'address',s.address,'township',s.township,'status',s.stop_status,'active_sequence',s.optimized_sequence,'original_sequence',s.stop_sequence,
      'notes',s.metadata->>'notes') order by coalesce(s.optimized_sequence,s.stop_sequence),s.stop_sequence),'[]'::jsonb)
      from public.be_wayplan_dispatch_stops s where s.wayplan_id=p_wayplan_id));
end $$;
revoke all on function public.be_wayplan_active_route_snapshot_v1(text) from public,anon;
grant execute on function public.be_wayplan_active_route_snapshot_v1(text) to authenticated;

-- Non-delivery-result route actions. DELIVERED continues through be_rider_wayplan_action so proof/payment/signature controls remain intact.
create or replace function public.be_wayplan_stop_event_action_v1(p_payload jsonb)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare
  v_identity jsonb:=private.be_field_primary_context_v101(); v_code text:=upper(coalesce(v_identity->>'worker_code','')); v_role text:=lower(coalesce(v_identity->>'role',''));
  v_wayplan text:=nullif(btrim(p_payload->>'wayplan_id'),''); v_delivery text:=nullif(btrim(p_payload->>'delivery_way_id'),'');
  v_event text:=upper(coalesce(p_payload->>'event_type','')); v_status text; v_version integer; v_orig integer; v_active integer;
begin
  if auth.uid() is null then return jsonb_build_object('ok',false,'error','AUTHENTICATED_FIELD_SESSION_REQUIRED'); end if;
  if v_role not in ('rider','driver') then return jsonb_build_object('ok',false,'error','PRIMARY_WORKER_REQUIRED'); end if;
  if v_event not in ('CUSTOMER_UNAVAILABLE','RESCHEDULE','RTO','SKIP') then return jsonb_build_object('ok',false,'error','INVALID_ROUTE_EVENT'); end if;
  if not exists(select 1 from public.be_wayplan_membership_v40 m where m.wayplan_id=v_wayplan and m.delivery_way_id=v_delivery and
    case v_role when 'driver' then upper(coalesce(m.driver_code,''))=v_code else upper(coalesce(m.rider_code,''))=v_code end)
  then return jsonb_build_object('ok',false,'error','WAYPLAN_NOT_ASSIGNED_TO_SIGNED_IN_WORKER'); end if;

  select stop_sequence,optimized_sequence into v_orig,v_active from public.be_wayplan_dispatch_stops where wayplan_id=v_wayplan and delivery_way_id=v_delivery for update;
  if not found then return jsonb_build_object('ok',false,'error','Wayplan stop not found'); end if;
  select max(route_version) into v_version from public.be_wayplan_route_versions_v1 where wayplan_id=v_wayplan;
  v_status:=case v_event when 'CUSTOMER_UNAVAILABLE' then 'CUSTOMER_UNAVAILABLE' when 'RESCHEDULE' then 'RESCHEDULED' when 'RTO' then 'RETURN_TO_WAREHOUSE' else 'SKIPPED' end;
  update public.be_wayplan_dispatch_stops set stop_status=v_status,rider_status=v_status,rider_action_at=now(),
    failed_reason=coalesce(nullif(p_payload->>'reason',''),failed_reason),updated_at=now(),
    metadata=coalesce(metadata,'{}'::jsonb)||jsonb_build_object('last_route_event',v_event,'last_route_event_at',now(),'last_route_event_by',v_code)
  where wayplan_id=v_wayplan and delivery_way_id=v_delivery;
  insert into public.be_wayplan_stop_events_v1(wayplan_id,delivery_way_id,event_type,route_version,original_stop_sequence,active_stop_sequence,actor_code,actor_role,payload)
  values(v_wayplan,v_delivery,v_event,v_version,v_orig,v_active,v_code,v_role,p_payload);
  return jsonb_build_object('ok',true,'wayplan_id',v_wayplan,'delivery_way_id',v_delivery,'event_type',v_event,'status',v_status,'reroute_remaining',true);
end $$;
revoke all on function public.be_wayplan_stop_event_action_v1(jsonb) from public,anon;
grant execute on function public.be_wayplan_stop_event_action_v1(jsonb) to authenticated;

-- Audit ARRIVED and DELIVERED generated through the existing proof-controlled action path.
create or replace function public.be_wayplan_audit_primary_stop_transition_v1()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare v_event text; v_version integer;
begin
  if coalesce(new.stop_status,'') is not distinct from coalesce(old.stop_status,'') then return new; end if;
  v_event:=case upper(coalesce(new.stop_status,'')) when 'ARRIVED_AT_CUSTOMER' then 'ARRIVED' when 'DELIVERED' then 'DELIVERED' else null end;
  if v_event is null then return new; end if;
  select max(route_version) into v_version from public.be_wayplan_route_versions_v1 where wayplan_id=new.wayplan_id;
  insert into public.be_wayplan_stop_events_v1(wayplan_id,delivery_way_id,event_type,route_version,original_stop_sequence,active_stop_sequence,actor_code,actor_role,payload)
  values(new.wayplan_id,new.delivery_way_id,v_event,v_version,new.stop_sequence,new.optimized_sequence,coalesce(new.rider_code,''),'rider',jsonb_build_object('stop_status',new.stop_status));
  return new;
end $$;
revoke all on function public.be_wayplan_audit_primary_stop_transition_v1() from public,anon,authenticated;
drop trigger if exists trg_be_wayplan_audit_primary_stop_transition_v1 on public.be_wayplan_dispatch_stops;
create trigger trg_be_wayplan_audit_primary_stop_transition_v1
after update of stop_status on public.be_wayplan_dispatch_stops
for each row execute function public.be_wayplan_audit_primary_stop_transition_v1();

-- Extend atomic multi-van generation. Existing 50-75, below-minimum approval and idempotency rules remain.
create or replace function public.be_generate_multi_van(p_payload jsonb)
returns jsonb language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare
 ctx jsonb; plans jsonb:=p_payload->'plans'; p jsonb; v jsonb; driver jsonb; rider jsonb; helper jsonb;
 request_id text:=p_payload->>'request_id'; region text:=upper(p_payload->>'region_code'); branch text;
 old_event jsonb; result jsonb; results jsonb:='[]'; ids text[]:='{}'; crews text[]:='{}'; vans text[]:='{}';
 parcel_id text; n int; short_count int:=0; total_count int:=0; weight numeric;
 reason text:=btrim(coalesce(p_payload->>'below_minimum_reason','')); actor text; plan_id text; idx int:=0;
 route jsonb; route_ids text[]; plan_ids text[]; route_source text; route_mode text; delivery_json jsonb; load_json jsonb;
begin
 ctx:=public.be_multi_van_context(); actor:=coalesce(auth.jwt()->>'email',auth.uid()::text);
 if request_id is null or request_id !~ '^[a-fA-F0-9-]{36}$' then raise exception 'A stable request ID is required.'; end if;
 if plans is null or jsonb_typeof(plans)<>'array' or jsonb_array_length(plans) not between 1 and 7 then raise exception 'Select one to seven delivery vans.'; end if;
 if region not in ('YANGON','MANDALAY','NAYPYITAW') then raise exception 'Choose an active delivery region.'; end if;
 branch:=case region when 'YANGON' then 'YGN' when 'MANDALAY' then 'MDY' else 'NPT' end;
 perform pg_advisory_xact_lock(hashtextextended('britium-multi-van-planner',0));
 select details into old_event from public.be_audit_events where action='MULTI_VAN_CREATED' and resource_id=request_id limit 1;
 if old_event is not null then
   if old_event->'request' is distinct from p_payload or old_event->>'actor_id'<>auth.uid()::text then raise exception 'Request ID already belongs to another operation.'; end if;
   return old_event->'result';
 end if;

 for p in select value from jsonb_array_elements(plans) loop
   n:=jsonb_array_length(p->'delivery_way_ids'); if n is null or n<1 then raise exception 'Each activated van needs parcels.'; end if;
   if n>75 then raise exception 'A delivery van cannot exceed 75 parcels.'; end if;
   total_count:=total_count+n; if n<50 then short_count:=short_count+1; end if;
   select x into v from jsonb_array_elements(ctx->'vehicles') x where x->>'id'=p->>'vehicle_code' and x->>'operation_type'='DELIVERY';
   if v is null then raise exception 'Choose a delivery van; pickup/highway vehicles are reserved.'; end if;
   if (p->>'vehicle_code')=any(vans) then raise exception 'A van cannot be allocated twice.'; end if; vans:=array_append(vans,p->>'vehicle_code');
   select x into driver from jsonb_array_elements(ctx->'drivers') x where x->>'id'=p->>'driver_code';
   select x into rider from jsonb_array_elements(ctx->'riders') x where x->>'id'=p->>'rider_code';
   if driver is null then raise exception 'Choose an active, authenticated Driver.'; end if;
   if rider is null then raise exception 'Choose an active, authenticated Rider.'; end if;
   if coalesce(driver->>'branch_code','') not in ('',branch) then raise exception 'Driver belongs to another branch.'; end if;
   if coalesce(rider->>'branch_code','') not in ('',branch) then raise exception 'Rider belongs to another branch.'; end if;
