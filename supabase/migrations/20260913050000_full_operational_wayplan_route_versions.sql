   update public.be_wayplan_dispatch_stops set stop_sequence=stop_sequence+100000 where wayplan_id=plan_id;
   update public.be_wayplan_dispatch_stops s set stop_sequence=x.ord::int,optimized_sequence=x.ord::int,route_code=plan_id||'-RV001',metadata=coalesce(s.metadata,'{}'::jsonb)||jsonb_build_object('generated_route_version',1,'active_route_version',1,'active_route_sequence',x.ord::int)
   from jsonb_array_elements_text(p->'delivery_way_ids') with ordinality x(id,ord) where s.wayplan_id=plan_id and s.delivery_way_id=x.id;

