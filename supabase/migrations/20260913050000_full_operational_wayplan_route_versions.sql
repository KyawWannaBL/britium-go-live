-- Full Operational Wayplan: immutable route versions, warehouse route snapshots,
-- Rider crew allocation and auditable stop events.
-- Additive migration. Existing Wayplans and historical warehouse data are not rewritten.

create table if not exists public.be_wayplan_route_versions_v1 (
  wayplan_id text not null,
  route_version integer not null check (route_version > 0),
  route_scope text not null check (route_scope in ('GENERATED','RIDER_REROUTE')),
  route_source text not null check (route_source in ('GOOGLE_ROUTES','MAPBOX_FALLBACK','GEOGRAPHIC_FALLBACK')),
  route_mode text not null,
  ordered_stops jsonb not null check (jsonb_typeof(ordered_stops)='array'),
  distance_m bigint not null default 0,
  duration_s bigint not null default 0,
  request_count integer not null default 0,
  parent_route_version integer,
  generated_by text,
  generated_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  primary key (wayplan_id, route_version)
);

create index if not exists idx_be_wayplan_route_versions_v1_latest
  on public.be_wayplan_route_versions_v1(wayplan_id, route_version desc);

create table if not exists public.be_wayplan_warehouse_load_snapshot_v1 (
  wayplan_id text primary key,
  generated_route_version integer not null,
  delivery_order jsonb not null check (jsonb_typeof(delivery_order)='array'),
  load_order jsonb not null check (jsonb_typeof(load_order)='array'),
  created_by text,
  created_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.be_wayplan_stop_events_v1 (
  id bigint generated by default as identity primary key,
  wayplan_id text not null,
  delivery_way_id text not null,
  event_type text not null check (event_type in ('ARRIVED','DELIVERED','CUSTOMER_UNAVAILABLE','RESCHEDULE','RTO','SKIP')),
  route_version integer,
  original_stop_sequence integer,
  active_stop_sequence integer,
  actor_code text,
  actor_role text,
  event_at timestamptz not null default now(),
  payload jsonb not null default '{}'::jsonb
);

create index if not exists idx_be_wayplan_stop_events_v1_wayplan
  on public.be_wayplan_stop_events_v1(wayplan_id,event_at,id);

alter table public.be_wayplan_route_versions_v1 enable row level security;
alter table public.be_wayplan_warehouse_load_snapshot_v1 enable row level security;
alter table public.be_wayplan_stop_events_v1 enable row level security;

