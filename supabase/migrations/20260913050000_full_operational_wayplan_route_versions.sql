   select coalesce(jsonb_agg(jsonb_build_object('delivery_way_id',s.delivery_way_id,'sequence',s.stop_sequence,'waybill_no',s.waybill_no,'recipient_name',s.recipient_name,'recipient_phone',s.recipient_phone,'address',s.address,'township',s.township) order by s.stop_sequence),'[]'::jsonb) into delivery_json from public.be_wayplan_dispatch_stops s where s.wayplan_id=plan_id;
   select coalesce(jsonb_agg(x.value order by x.ord desc),'[]'::jsonb) into load_json from jsonb_array_elements(delivery_json) with ordinality x(value,ord);
   insert into public.be_wayplan_route_versions_v1(wayplan_id,route_version,route_scope,route_source,route_mode,ordered_stops,distance_m,duration_s,request_count,generated_by,metadata)
   values(plan_id,1,'GENERATED',route_source,route_mode,delivery_json,greatest(coalesce(nullif(route->>'distance_m','')::bigint,0),0),greatest(coalesce(nullif(route->>'duration_s','')::bigint,0),0),greatest(coalesce(nullif(route->>'request_count','')::integer,0),0),actor,jsonb_build_object('fallback',coalesce((route->>'fallback')::boolean,false),'warning',route->>'warning','optimized_at',route->>'optimized_at'));
   insert into public.be_wayplan_warehouse_load_snapshot_v1(wayplan_id,generated_route_version,delivery_order,load_order,created_by,metadata)
   values(plan_id,1,delivery_json,load_json,actor,jsonb_build_object('load_strategy','LIFO','immutable_pre_dispatch_route',true));
   update public.be_wayplan_dispatches set metadata=coalesce(metadata,'{}'::jsonb)||jsonb_build_object('generated_route_version',1,'active_route_version',1,'warehouse_generated_route_version',1,'active_route_source',route_source,'active_route_mode',route_mode) where wayplan_id=plan_id;
   results:=results||jsonb_build_array(result||jsonb_build_object('generated_route_version',1,'route_source',route_source));
   if jsonb_array_length(p->'delivery_way_ids')<50 then insert into public.be_audit_events(actor_id,actor_email,actor_role,action,resource_type,resource_id,details) values(auth.uid(),actor,public.be_current_user_role(),'MULTI_VAN_BELOW_MINIMUM_APPROVED','WAYPLAN',plan_id,jsonb_build_object('vehicle',v,'parcel_count',jsonb_array_length(p->'delivery_way_ids'),'reason',reason,'request_id',request_id)); end if;
 end loop;
